"""Epics: a milestone on GitHub (progress, filtering) + `docs/epics/<slug>.md` in the repo
(the frame: why, scope, readiness — versioned next to the code).

The task list inside the file sits between markers and belongs to code (`h epic sync`,
Stage 5 step 3): nobody — agent or human — edits it by hand, so it cannot drift from the
issues. Everything outside the markers is written by the agent after discussing with the user.
"""

from __future__ import annotations

import hashlib
import re
import secrets
import shutil
import sys
from collections.abc import Callable
from pathlib import Path

from . import board, gh, lock, prreview, task
from .config import Config

EPICS_DIR = Path("docs") / "epics"
START = "<!-- h:tasks:start — generated by `h epic sync`, do not edit -->"
END = "<!-- h:tasks:end -->"
SLUG = re.compile(r"^[a-z0-9][a-z0-9-]{0,40}$")
# A publish worktree: pub-<branch with / as -><8 hex>.
PUB_DIR = re.compile(r"^pub-(.+)-[0-9a-f]{8}$")

TEMPLATE = """# Epic: {slug} — {title}

Milestone: `{slug}` · the epic's tasks are the issues with this milestone.

## Why

_TBD_

## Scope

_TBD_ (what is in, what is explicitly out)

## Done when

_TBD_ (when the epic counts as finished)

## Tasks

{start}
{end}
"""


def new(
    cfg: Config, slug: str, title: str, frame: str = ""
) -> tuple[str, bool, str | None]:
    """Milestone + epic file. The file is published by a small auto-merged PR, never left
    untracked in whatever checkout ran the command (seen 2026-10-22).
    Returns (relative path, milestone_created, PR url or None if the file already exists)."""
    if not SLUG.match(slug):
        raise ValueError(f"epic slug {slug!r}: lowercase letters, digits, '-'")
    rel = (EPICS_DIR / f"{slug}.md").as_posix()
    milestone_created = gh.ensure_milestone(cfg.root, slug, f"{title} — {rel}")
    text = TEMPLATE.format(slug=slug, title=title, start=START, end=END)
    if frame.strip():
        head, _, tail = text.partition("## Why")
        text = head + frame.strip() + "\n\n## Tasks" + tail.split("## Tasks", 1)[1]

    def create(root: Path) -> bool:
        path = root / rel
        if path.exists():
            return False
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        return True

    url = publish(
        cfg,
        cfg.auto_branch(f"epic-{slug}-new", f"chore/epic-{slug}-new"),
        f"docs(epic): {slug}",
        create,
        "",
    )
    return rel, milestone_created, url


def exists(cfg: Config, slug: str) -> bool:
    """An epic exists when its milestone does — the file may still be in a pending PR."""
    return slug in gh.milestones(cfg.root)


# --- task list block ---------------------------------------------------------------------


def task_lines(issues: list[dict]) -> list[str]:
    lines = []
    for i in sorted(issues, key=lambda i: i["number"]):
        closed = i["state"].upper() == "CLOSED"
        labels = [
            lb["name"] if isinstance(lb, dict) else lb for lb in i.get("labels", [])
        ]
        stage = board.stage_of(labels, closed)
        if "cleanup-blocked" in labels:
            stage += ", cleanup blocked"
        if stage == "Dropped":
            lines.append(f"- ~~#{i['number']} {i['title']}~~ — dropped")
            continue
        lines.append(
            f"- [{'x' if closed else ' '}] #{i['number']} {i['title']} — {stage}"
        )
    return lines


def render_block(text: str, lines: list[str]) -> str:
    if START not in text or END not in text:
        raise ValueError("epic file has no task block markers")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    body = "\n".join(lines)
    return f"{head}{START}\n{body}{chr(10) if body else ''}{END}{tail}"


def sync_text(cfg: Config, slug: str, text: str) -> str:
    return render_block(text, task_lines(gh.milestone_issues(cfg.root, slug)))


def status(cfg: Config) -> list[tuple[str, dict[str, int]]]:
    out = []
    for slug in sorted(gh.milestones(cfg.root)):
        counts: dict[str, int] = {}
        for i in gh.milestone_issues(cfg.root, slug):
            labels = [lb["name"] for lb in i.get("labels", [])]
            stage = board.stage_of(labels, i["state"].upper() == "CLOSED")
            if "cleanup-blocked" in labels:
                stage = "Cleanup blocked"
            counts[stage] = counts.get(stage, 0) + 1
        out.append((slug, counts))
    return out


# --- publishing through an auto-merged PR -------------------------------------------------


def publish(
    cfg: Config, branch: str, message: str, change: Callable[[Path], bool], body: str
) -> str | None:
    """Apply `change` to a fresh checkout of origin/<base> and land it through a PR with
    auto-merge — main is protected, and nobody's working tree is touched. Returns the PR
    url, or None when `change` had nothing to do.

    Publishes of one branch are serialized by a machine lock: two sessions syncing
    one epic at once removed each other's worktree and raced on fetch. The second waits
    and then rebuilds from the fresher origin. Each call gets its own worktree and removes
    only that one; worktrees of this branch left by a killed publish go first."""
    common = task.common_dir(cfg)
    name = branch.replace("/", "-")
    with lock.slot(1, _lock_name(common, name)):
        for path, state in leftovers(cfg, clean=True, own=name):
            if state == "failed":
                print(f"h: warning: could not remove {path}", file=sys.stderr)
        tmp = common / "harness" / f"pub-{name}-{secrets.token_hex(4)}"
        return _publish(cfg, tmp, branch, message, change, body)


def _lock_name(common: Path, name: str) -> str:
    repo = hashlib.sha1(str(common.resolve()).encode()).hexdigest()[:8]
    return f"pub-{repo}-{name}"


def leftovers(
    cfg: Config, clean: bool = False, own: str | None = None
) -> list[tuple[Path, str]]:
    """Publish worktrees no live publish uses: (path, "stale" | "removed" | "failed"), or
    "in use" when that branch's lock is held. `own` — the caller holds the lock of that
    branch: only its worktrees are looked at, without taking the lock again."""
    common = task.common_dir(cfg)
    main = task.main_root(cfg)
    out: list[tuple[Path, str]] = []
    base = common / "harness"
    for path in sorted(base.glob("pub-*")) if base.is_dir() else []:
        m = PUB_DIR.match(path.name)
        if not m or not path.is_dir() or (own is not None and m[1] != own):
            continue
        got = None if own is not None else lock.try_acquire(1, _lock_name(common, m[1]))
        if own is None and got is None:
            out.append((path, "in use"))
            continue
        try:
            if not clean:
                out.append((path, "stale"))
                continue
            task._git(main, "worktree", "remove", "--force", str(path))
            shutil.rmtree(path, ignore_errors=True)  # a dir git no longer knows about
            out.append((path, "failed" if path.exists() else "removed"))
        finally:
            if got is not None:
                lock.release(got[1])
    if any(state == "removed" for _, state in out):
        task._git(main, "worktree", "prune")
    return out


def _publish(
    cfg: Config,
    tmp: Path,
    branch: str,
    message: str,
    change: Callable[[Path], bool],
    body: str,
) -> str | None:
    main = task.main_root(cfg)
    task._ok(
        task._git(main, "fetch", "--quiet", "origin", cfg.base_branch), "git fetch"
    )
    task._ok(
        task._git(main, "worktree", "add", "--quiet", "-B", branch, str(tmp),
                  f"origin/{cfg.base_branch}"),
        "git worktree add",
    )  # fmt: skip
    try:
        if (
            not change(tmp)
            or not task._git(tmp, "status", "--porcelain").stdout.strip()
        ):
            return None
        task._git(tmp, "add", "--all")
        task._ok(task._git(tmp, "commit", "--quiet", "-m", message), "git commit")
        task._ok(
            task._git(tmp, "push", "--quiet", "--force", "-u", "origin", branch),
            "git push",
        )
        url = gh.pr_for_branch(cfg.root, branch)
        if url is None:
            url = gh.pr_create(cfg.root, branch, cfg.base_branch, message,
                               (body + "\n\n" if body else "") + "Published by `h`.")  # fmt: skip
        sha = task._ok(task._git(tmp, "rev-parse", "HEAD"), "git rev-parse").strip()
        # Generated epic lists, not code: the required review check must not hold them.
        try:
            prreview.publish_status(
                cfg, sha, "epic file generated by h — no code to review", url
            )
        except gh.GhError as err:  # auto-merge then waits on the required check
            print(f"h: warning: {prreview.STATUS_CONTEXT} not set on {url} ({err})",
                  file=sys.stderr)  # fmt: skip
        if not gh.pr_auto_merge(cfg.root, url):
            print(f"h: {url} is open, but this repository has auto-merge off — merge it "
                  "yourself, or allow it (Settings → General → Allow auto-merge)",
                  file=sys.stderr)  # fmt: skip
        return url
    finally:
        task._git(main, "worktree", "remove", "--force", str(tmp))
        task._git(main, "branch", "-D", branch)


def publish_sync(cfg: Config, slug: str) -> str | None:
    """Land the regenerated task block of one epic. One branch and one PR per epic: every
    publish rebuilds the block from all issues on top of origin/<base> and force-pushes,
    so a newer publish contains the older one instead of conflicting with it (two
    per-task PRs on the same block conflicted on 2026-10-22)."""
    rel = (EPICS_DIR / f"{slug}.md").as_posix()

    def tick(root: Path) -> bool:
        path = root / rel
        if not path.is_file():
            return False
        text = path.read_text(encoding="utf-8")
        new = sync_text(cfg, slug, text)
        if new == text:
            return False
        path.write_text(new, encoding="utf-8", newline="\n")
        return True

    return publish(
        cfg,
        cfg.auto_branch(f"epic-{slug}", f"chore/epic-{slug}"),
        f"chore(epic): sync {slug}",
        tick,
        "",
    )
